def classify(ingredient: str) -> str:
    name = (ingredient or "").strip()
    if not name:
        return "其他"
    if name in _EXACT:
        return _EXACT[name]
    for key, category in _KEYWORDS:
        if key in name:
            return category
    return "其他"


def aggregate(items: list[dict], *, extra: list[str] | None = None) -> list[dict]:
    """items 为 [{name, ingredients:[...]}]。返回按品类分组、组内按出现次数排序的清单。"""
    counter: Counter[str] = Counter()
    for item in items:
        for ingredient in item.get("ingredients") or []:
            text = str(ingredient).strip()
            if text:
                counter[text] += 1
    for item in extra or []:
        text = str(item).strip()
        if text:
            counter[text] += 1
    return group_counts(counter)


def group_counts(counter: Counter[str] | dict[str, int]) -> list[dict]:
    """{食材: 次数} → 按品类分组的结构化清单。"""
    grouped: dict[str, list[dict]] = {}
    for name, count in counter.items():
        if not name:
            continue
        grouped.setdefault(classify(name), []).append({"name": name, "count": int(count)})

    result: list[dict] = []
    for category in CATEGORY_ORDER:
        if category not in grouped:
            continue
        entries = sorted(grouped[category], key=lambda x: (-x["count"], x["name"]))
        result.append({"category": category, "icon": CATEGORY_ICON.get(category, "🛒"), "items": entries})
    return result


def merge_plans(plans: list) -> list[dict]:
    """把多餐（一天两餐）的购物清单合并去重，重复食材累加次数。"""
    counter: Counter[str] = Counter()
    for plan in plans:
        for group in getattr(plan, "shopping", None) or []:
            for item in group.get("items", []):
                name = str(item.get("name") or "").strip()
                if name:
                    counter[name] += int(item.get("count", 1) or 1)
    return group_counts(counter)


def to_text(shopping: list[dict], *, prefix: str = "") -> str:
    lines: list[str] = []
    if prefix:
        lines.append(prefix)
    for group in shopping:
        names = "、".join(
            f"{item['name']}×{item['count']}" if item["count"] > 1 else item["name"]
            for item in group["items"]
        )
        lines.append(f"{group.get('icon', '')} {group['category']}：{names}")
    return "\n".join(lines)


def to_plain_list(shopping: list[dict]) -> list[str]:
    out: list[str] = []
    for group in shopping:
        for item in group["items"]:
            out.append(item["name"])
    return out
